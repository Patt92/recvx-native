#!/usr/bin/env python3
"""Translate the original status/inventory subsystem for the host build.

Inputs (unchanged): src/ps2/veronica/prog/{sub1,itemview,fileview,message,flag}.c
and include/ps2/veronica/prog/*.h. Output: <out>/status/.

The files are compiled as complete translation units against the original
types.h (cleaned by tools/generate_types.py: PS2 SDK includes and pure hardware
structs removed). Every textual change is listed here; no game logic changes.

1) Include paths `../../../ps2/veronica/prog/x.h` -> `x.h`, `#pragma` removed.
2) sub1.c ItemSort: `((NJS_TEXNAME*)&st->pip[n])->texaddr` reads the third
   32-bit word of a 12-byte PS2 NJS_TEXNAME, i.e. pip[n + 2]. On the host the
   struct holds a 64-bit pointer, so the access is spelled pip[n + 2].
3) sub1.c's indexed draw setup builds a GS TEST_1 packet (alpha test GEQUAL 128
   with FAIL_KEEP, depth test GEQUAL) for the first pass. The hardware boundary
   is `CoreZbuffOffI()`.
4) sub1.c `memset(sitem.keep, NULL, 0x20000)`: NULL is the integer 0 for
   Metrowerks; spelled 0.
"""
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_native_tables import block  # noqa: E402

root, out = Path(sys.argv[1]), Path(sys.argv[2]) / 'status'
prog = root / 'src/ps2/veronica/prog'
inc = root / 'include/ps2/veronica/prog'
out.mkdir(parents=True, exist_ok=True)

for header in inc.glob('*.h'):
    if header.name != 'types.h':
        shutil.copyfile(header, out / header.name)
import subprocess  # noqa: E402
subprocess.run([sys.executable, str(root / 'tools/generate_types.py'), '--out', str(out / 'types.h'), '--no-check'],
               check=True, stdout=subprocess.DEVNULL)


def translate(name):
    s = (prog / (name + '.c')).read_text()
    s = re.sub(r'^#include "\.\./\.\./\.\./ps2/veronica/prog/(\w+\.h)"', r'#include "\1"', s, flags=re.M)
    s = re.sub(r'^#pragma.*$', '', s, flags=re.M)
    return s


sub1 = translate('sub1')
sub1, n = re.subn(r'\(\(NJS_TEXNAME\s*\*\)\s*&st->pip\[num1\]\)->texaddr', 'st->pip[num1 + 2]', sub1)
assert n == 6, n
a = sub1.index('void Ps2ZbuffOffI()')
sub1 = sub1[:a] + 'void Ps2ZbuffOffI()\n{\n    CoreZbuffOffI();\n}\n' + sub1[block(sub1, a):]
sub1, n = re.subn(r'memset\(sitem\.keep, NULL, 0x20000\);', 'memset(sitem.keep, 0, 0x20000);', sub1)
assert n == 1, n

sources = {'sub1': sub1}
for name in ('itemview', 'fileview', 'message', 'flag'):
    sources[name] = translate(name)
for name, text in sources.items():
    (out / (name + '.c')).write_text('/* Generated by tools/generate_status_sources.py from original %s.c; do not edit. */\n'
                                     '#include "status_platform.h"\n' % name + text)

# --- PS2 Ninja/GS platform routines ------------------------------------------
# The Ninja 2D draw routines and GS state setters are taken verbatim; they emit
# GIF packets into WORKBASE (scratchpad) and hand them to loadImage. The host GS
# (native/core_gs.cpp) executes those packets. Rewrites, all representation-only:
#  5) WORKBASE (fixed 0x70000000 scratchpad) -> host scratchpad array.
#  6) NJS_TEXNAME.texaddr uses a 32-bit EE pointer slot; the host stores an index
#     into the texture table (recvx_core_texmem()).
#  7) Original pointer stepping `(type*)((int)p + 48)` -> char pointer + 48.
#  8) VU0 conversion is supplied by the core boundary.
PLATFORM = [
    ('ps2_NaSprite', ['njDrawSprite2D']),
    ('ps2_NaDraw2D', ['CalcPs2ZbuffAB', 'njDrawLine2D', 'njDrawPolygon2D', 'njDrawPolygon2DM']),
    ('ps2_NaDraw', ['njDrawTextureSub', 'njDrawTexture', 'njDrawTextureSubH', 'njDrawTextureH']),
    ('ps2_NaSystem', ['njTextureFilterMode', 'njColorBlendingModeSys', 'njColorBlendingMode', 'njUserClipping']),
    ('ps2_NaTextureFunction', ['SearchNumber', 'njSetTexture', 'njSetTextureNum', 'njSetTextureNumSys',
                               'njSetPaletteBankNum', 'njSetPaletteMode']),
    ('ps2_NinjaCnk', ['njSetConstantAttr', 'njSetConstantMaterial']),
    ('ps2_dummy', ['Ps2AddPrim', 'Ps2AddPrim2D', 'Ps2GlobalIndexTexLoad', 'Ps2SetFogColor', 'Ps2SetFogColorSys',
                   'Ps2ZbuffOff', 'Ps2ZbuffOff2', 'Ps2ZbuffOn', 'Ps2AlphaIs000', 'Ps2AlphaIsHalf',
                   'Ps2Alpha4to8', 'Ps2CheckTextureAlpha', 'Ps2TexLoad']),
    ('ps2_texture', ['ClutCopy', 'ClutCopy256', 'isVQ', 'bhSetMemPvpTexture', 'bhGarbageTexture']),
    ('ps2_NaTextureFunction', ['SearchNullNumber', 'njLoadTexture', 'njReleaseTexture', 'njSetTextureInfo',
                               'njSetTextureName']),
    # The indexed draw entry points use PS2 list pointers and EE packet addresses;
    # the core boundary translates their observable OT operation instead.

]


def function(text, name):
    m = re.search(r'^[A-Za-z_][\w \t\*]*?\b' + name + r'\s*\([^;{]*\)\s*(?://[^\n]*)?\s*\{', text, re.M)
    if not m:
        raise RuntimeError('missing platform routine ' + name)
    return text[m.start():block(text, m.start())]


# PS2-only OT allocator/global lists are not emitted on a 64-bit host; the core GS
# owns the ordering table. These boundaries preserve sorting and state transitions.
PLATFORM_OT = '''\nvoid CoreClearOT(void) { recvx_core_gs_ot_clear(); }\n\nvoid CoreAddOT(void* p, unsigned int num, float z, unsigned long prim)\n{\n    unsigned int otz = z > 0.0f ? ((unsigned int)z >> 4) : 0;\n    unsigned int qwords = num * 3 + 1;\n    const uint64_t* packet = (const uint64_t*)p;\n    recvx_core_gs_ot_add(otz, Ps2_now_tex, Ps2_now_bank, Ps2_gs_save.ALPHA, packet + 6, qwords);\n    (void)prim;\n}\n\nvoid CoreDrawOTag(void) { recvx_core_gs_ot_draw(); Ps2_current_texbreak = 1; }\n\nunsigned int CoreBitCount(register unsigned int value)\n{ unsigned int n = 0; while (value) { ++n; value >>= 1; } return n; }\n'''

# Original global definitions of these routines, copied as written.
GLOBALS = [
    ('ps2_NaDraw2D', ['Ps2_zbuff_a', 'Ps2_zbuff_b']),
    ('ps2_NinjaCnk', ['ucNaCnkAttr', 'fNaCnkConstantA', 'fNaCnkConstantR', 'fNaCnkConstantG', 'fNaCnkConstantB',
                      'NaCnkConstantMaterial']),
    ('ps2_NaSystem', ['Ps2_nj_save_current']),
    ('ps2_NaTextureFunction', ['Ps2_tex_info', 'Ps2_texmemlist_num', 'Ps2_current_texlist', 'Ps2_current_texno',
                               'Ps2_current_texmemlist', 'Ps2_current_gindex', 'Ps2_texcontinue_no']),
    ('ps2_dummy', ['Ps2_gs_save', 'Ps2_now_tex', 'Ps2_now_bank', 'Ps2_use_pt_flag', 'Ps2_tex_load_tp_cancel',
                   'Ps2_ice_flag', 'palbuf', 'ViewType', 'Ps2_tex_cache_buff', 'Ps2_tex_cache_beflag',
                   'Ps2_tex_cache_num', 'PS2_Render_tex_sub_flag']),
    ('ps2_NaView', ['fNaViwClipNear', 'fNaViwClipFar']),
    ('ps2_texture', ['info', 'tlist']),
]
platform = []
for file, names in GLOBALS:
    text = (prog / (file + '.c')).read_text()
    for name in names:
        m = re.search(r'^(?!extern)[A-Za-z_][^\n(;]*\b' + name + r'\b[^\n;]*;', text, re.M)
        if not m:
            raise RuntimeError('missing platform global ' + name)
        platform.append('/* %s.c */ ' % file + m.group(0))
for file, names in PLATFORM:
    text = (prog / (file + '.c')).read_text()
    for name in names:
        platform.append('/* %s.c */\n' % file + function(text, name))
platform = '\n\n'.join(platform)
# Host-core boundaries replace PS2 SDK/OT entry points; original game routines
# retain their original bh*/nj*/Ps2* names where those are part of the engine.
platform = platform.replace('Ps2AddOT(', 'CoreAddOT(').replace('Ps2ClearOT(', 'CoreClearOT(')\
                    .replace('Ps2DrawOTag(', 'CoreDrawOTag(').replace('Ps2BitCount(', 'CoreBitCount(')
platform += '\n' + PLATFORM_OT
platform, n = re.subn(r'\(\s*NJS_TEXMEMLIST\s*\*\s*\)\s*([\w>\-\.]+(?:\[[^\]]*\])?[\w>\-\.]*?\.texaddr)',
                      r'recvx_core_texmem(\1)', platform)
assert n >= 6, n
platform, n = re.subn(r'\(\s*unsigned int\s*\)\s*&addr\[(\w+)\]', r'(unsigned int)(\1)', platform)
assert n == 3, n
# 10) Metrowerks lvalue-cast post-increment and int-sized pointer arithmetic.
platform, n = re.subn(r'palnum = \*\(\(int\*\)ap\)\+\+;', 'palnum = *(int*)ap; ap += 4;', platform)
assert n == 1, n
platform, n = re.subn(r'sz = \(int\)&palbuf\[\(\(bk_id / 64\) \* 64\) \* 16\];', 'palsrc = (unsigned char*)&palbuf[((bk_id / 64) * 64) * 16];', platform)
assert n == 1, n
platform, n = re.subn(r'palp = \(unsigned char\*\)\(palno \+ sz\);', 'palp = palsrc + palno;', platform)
assert n == 1, n
platform = platform.replace('    unsigned char* palp;  \n', '    unsigned char* palp;  \n    unsigned char* palsrc;\n', 1)
platform, n = re.subn(r'cp = \(unsigned int\*\)\(\(int\)pp \+ temp2->ImageSize \+ 256\);', 'cp = (unsigned int*)((char*)pp + temp2->ImageSize + 256);', platform)
assert n == 1, n
platform, n = re.subn(r'\(\s*(unsigned long|UNKNOWN)\s*\*\s*\)\s*\(\s*\(\s*int\s*\)\s*(\w+)\s*\+\s*48\s*\)',
                      r'(\1*)((char*)\2 + 48)', platform)
assert n == 2, n
# 11) sceGsTex0 is a libgraph bitfield struct; TBW is bits 14-19 of the register word.
platform, n = re.subn(r'(\w+)->GsTex0\.TBW', r'((\1->GsTex0 >> 14) & 0x3f)', platform)
assert n == 1, n
# 9) TIM2_PICTUREHEADER_EX is removed from the cleaned types.h with the SDK; its
#    original definition is emitted with the libgraph bitfield registers
#    sceGsTex0/sceGsTex1 spelled as their 64-bit register words.
types = (inc / 'types.h').read_text()
a = types.index('typedef struct TIM2_PICTUREHEADER_EX')
tim2 = types[a:types.index('} TIM2_PICTUREHEADER_EX;', a) + len('} TIM2_PICTUREHEADER_EX;')]
tim2, n = re.subn(r'\bsceGsTex[01]\b', 'unsigned long', tim2)
assert n == 2, n
# ADMIN's addr/before/after are 32-bit VRAM ring links inside the file header;
# the host keeps the file layout (0xD0 bytes) and never follows those links.
tim2, n = re.subn(r'ADMIN admin;', 'struct {unsigned int gindex, size, count, addr, before, after;} admin;', tim2)
assert n == 1, n
tim2 += '\n_Static_assert(sizeof(TIM2_PICTUREHEADER_EX) == 0xD0, "TIM2 header layout");'
(out / 'tim2.h').write_text('/* Generated from include/ps2/veronica/prog/types.h; do not edit. */\n'
                            '#ifndef RECVX_TIM2_H\n#define RECVX_TIM2_H\n#include "types.h"\n' + tim2 + '\n#endif\n')
(out / 'ninja2d.c').write_text('/* Generated by tools/generate_status_sources.py from original engine platform routines; do not edit. */\n'
                               '#include "core_platform.h"\n' + platform + '\n')
